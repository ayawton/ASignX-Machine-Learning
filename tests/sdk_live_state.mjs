import assert from 'node:assert/strict';
import fs from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=fs.readFileSync(new URL('../web_client/asignx_client_sdk.ts',import.meta.url),'utf8');
const sdk=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(source)).toString('base64'));
const meta={model_type:'static_sign_resmlp',labels:['A','B'],input_dim:63,hidden_sizes:[128,64],use_kinematic_features:true,use_cosine_head:true};
const raw=Array.from({length:21},(_,i)=>({x:.1+i*.001,y:.2+i*.002,z:0}));
const a=new Float32Array([10,-10]),b=new Float32Array([-10,10]);
const state=new sdk.ASignLiveStabilizer(meta,.8,2,2);
assert.equal(state.update('Left',raw,a,0).stableLabel,null);
assert.equal(state.update('Right',raw,b,0).stableLabel,null);
assert.equal(state.update('Left',raw,a,.04).emittedLabel,'A');
assert.equal(state.update('Right',raw,b,.04).emittedLabel,'B');
assert.equal(state.update('Left',raw,b,.08).stableLabel,null);
assert.equal(state.update('Left',raw,b,.12).stableLabel,'B');
state.markHandMissing('Left');
assert.equal(state.update('Left',raw,b,.16).stableLabel,null);
assert.equal(state.update('Right',raw,b,.16).stableLabel,'B');
assert.equal(state.update('Right',raw,b,1).stableLabel,null);
assert.equal(state.update('Right',raw,b,1.04).emittedLabel,'B');
assert.throws(()=>state.update('Right',raw,b,1.04),/timestamps/);
state.markHandMissing();state.markHandMissing();
assert.equal(state.update('Right',raw,b,1.08).stableLabel,null);
assert.equal(state.update('Right',raw,b,1.12).emittedLabel,'B');
state.reset('Right');assert.equal(state.update('Right',raw,b,0).stableLabel,null);
const coach=new sdk.ASignLearnCoach(meta,2,.75);
assert.equal(coach.evaluateAttempt(new Float32Array(63),a,'A').holdProgress,.5);
const changed=coach.evaluateAttempt(new Float32Array(63),b,' b ');
assert.equal(changed.passed,false);assert.equal(changed.holdProgress,.5);
assert.ok(changed.fingerFeedback.every(f=>f.meanError===null && f.isAligned===null && !f.referenceAvailable));
assert.ok(changed.fingerFeedback.every(f=>f.hint.includes('unavailable')));
assert.equal(coach.evaluateAttempt(new Float32Array(63),b,'B').passed,true);
coach.reset();assert.equal(coach.evaluateAttempt(new Float32Array(63),b,'B').passed,false);
const references=new sdk.ASignLearnCoach({...meta,class_centroids:{A:Array(63).fill(0)}},2,.75);
assert.ok(references.evaluateAttempt(new Float32Array(63),a,'A').fingerFeedback.every(f=>f.referenceAvailable && f.isAligned===true));
console.log('SDK hand isolation, stale-state clearing, gap recovery, emission and coaching regressions passed.');
